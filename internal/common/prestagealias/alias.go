// Package prestagealias holds the rules the two PreStage resources share for renaming a
// top-level or account_settings attribute without breaking configurations that still use the old
// name. internal/common/prestageskip does the same for the skip_setup_items checklist.
//
// A rename ships as a pair: the new attribute carries the admin UI's name, and the old one stays
// for the deprecation window. Both are Optional and Computed and both map to one wire field.
// Three rules keep the pair consistent:
//
//   - A ConflictsWith validator forbids setting both in one configuration.
//   - ReconcilePlan copies whichever one is configured into the other during planning, so the
//     plan never disagrees with the single value the API stores. A pair flagged Invert holds
//     opposite booleans (Jamf Pro's mobile "Prevent Unenrollment" is the inverse of the wire's
//     mdmRemovable), and the copy negates.
//   - CarryAlias populates the old attribute from the API only when state already holds it, so a
//     configuration generated by import or `terraform query` names the new attribute alone.
//
// A deprecation with no replacement attribute (a value Jamf Pro derives from another attribute)
// is not a Pair. Its attribute is Optional only: the provider derives the wire value and uses the
// configured one only to agree with it, so state holds exactly what the author wrote.
package prestagealias

import (
	"context"
	"fmt"

	"github.com/hashicorp/terraform-plugin-framework-validators/boolvalidator"
	"github.com/hashicorp/terraform-plugin-framework-validators/setvalidator"
	"github.com/hashicorp/terraform-plugin-framework-validators/stringvalidator"
	"github.com/hashicorp/terraform-plugin-framework/attr"
	"github.com/hashicorp/terraform-plugin-framework/diag"
	"github.com/hashicorp/terraform-plugin-framework/path"
	"github.com/hashicorp/terraform-plugin-framework/resource"
	"github.com/hashicorp/terraform-plugin-framework/schema/validator"
	"github.com/hashicorp/terraform-plugin-framework/types"
	"github.com/hashicorp/terraform-plugin-go/tftypes"
)

// Pair names a deprecated attribute and the attribute that replaces it.
type Pair struct {
	// Parent is the object attribute both live in, or empty when they are top-level.
	Parent string
	// Old is the deprecated attribute and New its replacement.
	Old, New string
	// Invert marks a boolean pair whose two attributes hold opposite values.
	Invert bool
}

func (p Pair) path(name string) path.Path {
	if p.Parent == "" {
		return path.Root(name)
	}
	return path.Root(p.Parent).AtName(name)
}

// BoolConflicts returns the validators for a deprecated bool: setting it alongside its
// replacement is a configuration error.
func BoolConflicts(replacement string) []validator.Bool {
	return []validator.Bool{boolvalidator.ConflictsWith(sibling(replacement))}
}

// StringConflicts is BoolConflicts for a string attribute.
func StringConflicts(replacement string) []validator.String {
	return []validator.String{stringvalidator.ConflictsWith(sibling(replacement))}
}

// SetConflicts is BoolConflicts for a set attribute.
func SetConflicts(replacement string) []validator.Set {
	return []validator.Set{setvalidator.ConflictsWith(sibling(replacement))}
}

// BoolAtLeastOne returns the validator for the replacement of an attribute that used to be
// Required: one of the two names must be set, as before the rename.
func BoolAtLeastOne(deprecated string) []validator.Bool {
	return []validator.Bool{boolvalidator.AtLeastOneOf(sibling(deprecated))}
}

// StringAtLeastOne is BoolAtLeastOne for a string attribute.
func StringAtLeastOne(deprecated string) []validator.String {
	return []validator.String{stringvalidator.AtLeastOneOf(sibling(deprecated))}
}

// SetAtLeastOne is BoolAtLeastOne for a set attribute.
func SetAtLeastOne(deprecated string) []validator.Set {
	return []validator.Set{setvalidator.AtLeastOneOf(sibling(deprecated))}
}

func sibling(name string) path.Expression {
	return path.MatchRelative().AtParent().AtName(name)
}

// Resolution is what ReconcilePlan writes into the plan for one pair.
type Resolution struct {
	SetNew bool
	New    attr.Value
	SetOld bool
	Old    attr.Value
}

// Resolve decides the planned value of a pair from the configured values and the prior state of
// the deprecated attribute.
//
// The replacement takes the configured value of whichever attribute the author wrote. The
// deprecated attribute follows it only while state already holds one: when state holds none the
// plan says null, so the attribute stays absent for anyone who never used it. Nothing is written
// while either configured value is still unknown, which leaves the planned value for apply to
// settle.
func Resolve(ctx context.Context, cfgNew, cfgOld, stateOld attr.Value, invert bool) Resolution {
	if cfgNew.IsUnknown() || cfgOld.IsUnknown() {
		return Resolution{}
	}
	var effective attr.Value
	switch {
	case !cfgNew.IsNull():
		effective = cfgNew
	case !cfgOld.IsNull():
		effective = negateIf(invert, cfgOld)
	}

	var out Resolution
	if effective != nil && cfgNew.IsNull() {
		out.SetNew, out.New = true, effective
	}
	if !cfgOld.IsNull() {
		return out
	}
	out.SetOld = true
	switch {
	case effective != nil && !stateOld.IsNull():
		out.Old = negateIf(invert, effective)
	case effective == nil && !stateOld.IsNull():
		out.Old = stateOld
	default:
		out.Old = nullOf(ctx, cfgOld)
	}
	return out
}

// ReconcilePlan applies Resolve to every pair. Call it from ModifyPlan.
func ReconcilePlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse, pairs []Pair) {
	if req.Plan.Raw.IsNull() {
		return
	}
	for _, p := range pairs {
		cfgNew, ok := read(ctx, req.Config, p.path(p.New), &resp.Diagnostics)
		if !ok {
			continue
		}
		cfgOld, ok := read(ctx, req.Config, p.path(p.Old), &resp.Diagnostics)
		if !ok {
			continue
		}
		stateOld := nullOf(ctx, cfgOld)
		if !req.State.Raw.IsNull() {
			if v, ok := read(ctx, req.State, p.path(p.Old), &resp.Diagnostics); ok {
				stateOld = v
			}
		}
		if resp.Diagnostics.HasError() {
			return
		}
		r := Resolve(ctx, cfgNew, cfgOld, stateOld, p.Invert)
		if r.SetNew {
			resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, p.path(p.New), r.New)...)
		}
		if r.SetOld {
			resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, p.path(p.Old), r.Old)...)
		}
	}
}

// read fetches one attribute. A nested attribute under a block the author left out reads as
// null.
func read(ctx context.Context, src interface {
	GetAttribute(context.Context, path.Path, any) diag.Diagnostics
}, p path.Path, diags *diag.Diagnostics,
) (attr.Value, bool) {
	var v attr.Value
	d := src.GetAttribute(ctx, p, &v)
	if d.HasError() {
		diags.Append(d...)
		return nil, false
	}
	return v, v != nil
}

func negateIf(invert bool, v attr.Value) attr.Value {
	if !invert {
		return v
	}
	b, ok := v.(types.Bool)
	if !ok {
		panic(fmt.Sprintf("prestagealias: Invert needs a bool pair, got %s", v.Type(context.Background())))
	}
	if b.IsNull() || b.IsUnknown() {
		return b
	}
	return types.BoolValue(!b.ValueBool())
}

func nullOf(ctx context.Context, like attr.Value) attr.Value {
	t := like.Type(ctx)
	v, err := t.ValueFromTerraform(ctx, tftypes.NewValue(t.TerraformType(ctx), nil))
	if err != nil {
		panic(fmt.Sprintf("prestagealias: null %s: %v", t, err))
	}
	return v
}

// Effective returns the value to send for a pair when nothing else holds one: the replacement
// when the plan holds one, then the deprecated attribute (negated for an Invert pair), then
// fallback. Update passes the value Jamf Pro holds just before the write, so an attribute the
// plan leaves unknown keeps its server value instead of being reset.
func Effective(replacement, deprecated types.Bool, invert bool, fallback bool) bool {
	if !replacement.IsNull() && !replacement.IsUnknown() {
		return replacement.ValueBool()
	}
	if !deprecated.IsNull() && !deprecated.IsUnknown() {
		return deprecated.ValueBool() != invert
	}
	return fallback
}

// EffectiveString is Effective for strings: the replacement, then the deprecated attribute, then
// fallback.
func EffectiveString(replacement, deprecated types.String, fallback string) string {
	if !replacement.IsNull() && !replacement.IsUnknown() {
		return replacement.ValueString()
	}
	if !deprecated.IsNull() && !deprecated.IsUnknown() {
		return deprecated.ValueString()
	}
	return fallback
}

// CarryBool returns the value to store for a deprecated bool after a read. It is the wire value
// (negated for an Invert pair) when prior already holds one, and null otherwise, so import and
// config generation never produce the deprecated name.
func CarryBool(prior types.Bool, newValue bool, invert bool) types.Bool {
	if prior.IsNull() || prior.IsUnknown() {
		return types.BoolNull()
	}
	return types.BoolValue(newValue != invert)
}

// CarryString is CarryBool for strings.
func CarryString(prior types.String, newValue string) types.String {
	if prior.IsNull() || prior.IsUnknown() {
		return types.StringNull()
	}
	return types.StringValue(newValue)
}

// CarrySet is CarryBool for sets: it returns newValue when prior holds a set, and a null set of
// the same element type otherwise.
func CarrySet(prior types.Set, newValue types.Set) types.Set {
	if prior.IsNull() || prior.IsUnknown() {
		return types.SetNull(newValue.ElementType(context.Background()))
	}
	return newValue
}
