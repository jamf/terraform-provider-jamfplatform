// Package prestageskip holds the rules the two PreStage resources share for renaming a
// skip_setup_items attribute without breaking configurations that still use the old name.
//
// A rename ships as a pair: the new attribute carries the admin UI's name, and the old one stays
// for the deprecation window. Both are Optional and Computed booleans inside the skip_setup_items
// block, and both map to one wire key. Three rules keep the pair consistent:
//
//   - ConflictsWith forbids setting both in one configuration.
//   - ReconcilePlan copies whichever one is configured into the other during planning, so the
//     plan never disagrees with the single value the API stores.
//   - CarryAlias populates the old attribute from the API only when state already holds it, so a
//     configuration generated by import or `terraform query` names the new attribute alone.
package prestageskip

import (
	"context"

	"github.com/hashicorp/terraform-plugin-framework-validators/boolvalidator"
	"github.com/hashicorp/terraform-plugin-framework/attr"
	"github.com/hashicorp/terraform-plugin-framework/diag"
	"github.com/hashicorp/terraform-plugin-framework/path"
	"github.com/hashicorp/terraform-plugin-framework/resource"
	"github.com/hashicorp/terraform-plugin-framework/schema/validator"
	"github.com/hashicorp/terraform-plugin-framework/types"
)

// Block is the attribute that holds the checklist in both PreStage resources.
const Block = "skip_setup_items"

// Alias names a deprecated attribute and the attribute that replaces it. Both live directly under
// the skip_setup_items block.
type Alias struct {
	Old string
	New string
}

// Conflicts returns the validators for the deprecated attribute: setting it alongside its
// replacement is a configuration error.
func Conflicts(replacement string) []validator.Bool {
	return []validator.Bool{
		boolvalidator.ConflictsWith(path.MatchRelative().AtParent().AtName(replacement)),
	}
}

// Resolution is what ReconcilePlan writes into the plan for one alias pair.
type Resolution struct {
	SetNew bool
	New    types.Bool
	SetOld bool
	Old    types.Bool
}

// Resolve decides the planned value of an alias pair from the configured values and the prior
// state of the deprecated attribute.
//
// The replacement takes the configured value of whichever attribute the author wrote. The
// deprecated attribute follows it only while state already holds one: when state holds none the
// plan says null, so the attribute stays absent for anyone who never used it. Nothing is written
// while either configured value is still unknown, which leaves the planned value for apply to
// settle.
func Resolve(cfgNew, cfgOld, stateOld types.Bool) Resolution {
	if cfgNew.IsUnknown() || cfgOld.IsUnknown() {
		return Resolution{}
	}
	effective, ok := cfgNew, !cfgNew.IsNull()
	if !ok {
		effective, ok = cfgOld, !cfgOld.IsNull()
	}

	var out Resolution
	if ok && cfgNew.IsNull() {
		out.SetNew, out.New = true, effective
	}
	if !cfgOld.IsNull() {
		return out
	}
	switch {
	case ok:
		if !stateOld.IsNull() {
			out.SetOld, out.Old = true, effective
		} else {
			out.SetOld, out.Old = true, types.BoolNull()
		}
	case !stateOld.IsNull():
		out.SetOld, out.Old = true, stateOld
	default:
		out.SetOld, out.Old = true, types.BoolNull()
	}
	return out
}

// ReconcilePlan applies Resolve to every alias pair. Call it from ModifyPlan.
func ReconcilePlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse, aliases []Alias) {
	if req.Plan.Raw.IsNull() {
		return
	}
	block := path.Root(Block)

	var planBlock, cfgBlock types.Object
	resp.Diagnostics.Append(req.Plan.GetAttribute(ctx, block, &planBlock)...)
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, block, &cfgBlock)...)
	if resp.Diagnostics.HasError() || planBlock.IsNull() || planBlock.IsUnknown() || cfgBlock.IsNull() || cfgBlock.IsUnknown() {
		return
	}

	var stateBlock types.Object
	if !req.State.Raw.IsNull() {
		resp.Diagnostics.Append(req.State.GetAttribute(ctx, block, &stateBlock)...)
		if resp.Diagnostics.HasError() {
			return
		}
	}

	for _, a := range aliases {
		cfgNew := attrBool(cfgBlock, a.New, &resp.Diagnostics)
		cfgOld := attrBool(cfgBlock, a.Old, &resp.Diagnostics)
		stateOld := types.BoolNull()
		if !stateBlock.IsNull() && !stateBlock.IsUnknown() {
			stateOld = attrBool(stateBlock, a.Old, &resp.Diagnostics)
		}
		if resp.Diagnostics.HasError() {
			return
		}
		r := Resolve(cfgNew, cfgOld, stateOld)
		if r.SetNew {
			resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, block.AtName(a.New), r.New)...)
		}
		if r.SetOld {
			resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, block.AtName(a.Old), r.Old)...)
		}
	}
}

func attrBool(obj types.Object, name string, diags *diag.Diagnostics) types.Bool {
	v, ok := obj.Attributes()[name]
	if !ok || v == nil {
		return types.BoolNull()
	}
	b, ok := v.(types.Bool)
	if !ok {
		diags.AddError("Unexpected skip_setup_items attribute type", "attribute `"+name+"` is "+attrTypeName(v)+", not a bool")
		return types.BoolNull()
	}
	return b
}

func attrTypeName(v attr.Value) string {
	return v.Type(context.Background()).String()
}

// Effective returns the value to send for an alias pair when nothing else holds one: the
// replacement when the plan holds one, then the deprecated attribute, then false.
func Effective(replacement, deprecated types.Bool) bool {
	return EffectiveOr(replacement, deprecated, false)
}

// EffectiveOr is Effective with an explicit last resort. Update passes the value Jamf Pro holds
// just before the write, so a pane the plan leaves unknown keeps its server value instead of
// being reset to false.
func EffectiveOr(replacement, deprecated types.Bool, fallback bool) bool {
	if !replacement.IsNull() && !replacement.IsUnknown() {
		return replacement.ValueBool()
	}
	if !deprecated.IsNull() && !deprecated.IsUnknown() {
		return deprecated.ValueBool()
	}
	return fallback
}

// CarryAlias returns the value to store for a deprecated attribute after a read. It is the wire
// value when prior already holds one, and null otherwise, so import and config generation never
// produce the deprecated name.
func CarryAlias(prior types.Bool, wire bool) types.Bool {
	if prior.IsNull() || prior.IsUnknown() {
		return types.BoolNull()
	}
	return types.BoolValue(wire)
}
