// minJamfProVersion is the minimum Jamf Pro tenant version required by this
// resource. Empty: the classic /computerinvitations endpoint predates the
// provider's overall floor. The provider-level advisory still fires through
// providerdata.ConfigureProClassic when the tenant is below
// ProviderMinJamfProVersion.
const minJamfProVersion = ""

// ComputerInvitationResource implements the Terraform resource for Jamf Pro
// computer enrollment invitations.
type ComputerInvitationResource struct {
	client *proclassic.Client
}

var (
	_ resource.Resource                = &ComputerInvitationResource{}
	_ resource.ResourceWithImportState = &ComputerInvitationResource{}
	_ resource.ResourceWithIdentity    = &ComputerInvitationResource{}
)

const (
	defaultCreateTimeout = 60 * time.Second
	defaultReadTimeout   = 60 * time.Second
	defaultUpdateTimeout = 60 * time.Second
	defaultDeleteTimeout = 60 * time.Second
)

// NewComputerInvitationResource returns a new instance of
// ComputerInvitationResource.
func NewComputerInvitationResource() resource.Resource {
	return &ComputerInvitationResource{}
}

// Metadata sets the resource type name for the Terraform provider.
func (r *ComputerInvitationResource) Metadata(ctx context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_pro_computer_invitation"
}

// IdentitySchema defines the identifier used for import and list results.
func (r *ComputerInvitationResource) IdentitySchema(ctx context.Context, req resource.IdentitySchemaRequest, resp *resource.IdentitySchemaResponse) {
	resp.IdentitySchema = identityschema.Schema{
		Attributes: map[string]identityschema.Attribute{
			"id": identityschema.StringAttribute{
				Description:       "Jamf Pro computer invitation numeric ID used to uniquely reference the invitation.",
				RequiredForImport: true,
			},
		},
	}
}

