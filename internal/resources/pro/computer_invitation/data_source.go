// ComputerInvitationDataSource implements the Terraform data source for Jamf Pro
// computer invitations. Selection is by numeric `id` OR by the server-minted
// `invitation` code (the UI "Invitation ID") — exactly one of the two. There is
// no name lookup because invitations carry no name on the wire.
type ComputerInvitationDataSource struct {
	client *proclassic.Client
}

var (
	_ datasource.DataSource                     = &ComputerInvitationDataSource{}
	_ datasource.DataSourceWithConfigure        = &ComputerInvitationDataSource{}
	_ datasource.DataSourceWithConfigValidators = &ComputerInvitationDataSource{}
)

// NewComputerInvitationDataSource returns a new instance of
// ComputerInvitationDataSource.
func NewComputerInvitationDataSource() datasource.DataSource {
	return &ComputerInvitationDataSource{}
}

// Metadata sets the data source type name for the Terraform provider.
func (d *ComputerInvitationDataSource) Metadata(ctx context.Context, req datasource.MetadataRequest, resp *datasource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_pro_computer_invitation"
}

