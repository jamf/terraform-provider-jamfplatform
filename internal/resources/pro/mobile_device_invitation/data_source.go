// ConfigValidators enforces that exactly one of id / invitation is supplied.
func (d *MobileDeviceInvitationDataSource) ConfigValidators(ctx context.Context) []datasource.ConfigValidator {
	return []datasource.ConfigValidator{
		datasourcevalidator.ExactlyOneOf(
			path.MatchRoot("id"),
			path.MatchRoot("invitation"),
		),
	}
}

// Configure wires the Jamf ProClassic client into the data source via the
// shared providerdata.ConfigureProClassic helper.
func (d *MobileDeviceInvitationDataSource) Configure(ctx context.Context, req datasource.ConfigureRequest, resp *datasource.ConfigureResponse) {
	client, diags := providerdata.ConfigureProClassic(ctx, req.ProviderData, minJamfProVersion, "jamfplatform_pro_mobile_device_invitation")
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}
	d.client = client
}

// Read fetches a mobile device invitation by ID or by invitation code and
// populates Terraform state.
func (d *MobileDeviceInvitationDataSource) Read(ctx context.Context, req datasource.ReadRequest, resp *datasource.ReadResponse) {
	if d.client == nil {
		resp.Diagnostics.AddError(
			"Provider not configured",
			"The provider client was not configured. Please ensure the provider block is set up correctly.",
		)
		return
	}

	var data MobileDeviceInvitationDataSourceModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}

	readTimeout, timeoutDiags := helpers.ResolveTimeout(ctx, data.Timeouts.IsNull(), data.Timeouts.IsUnknown(), defaultReadTimeout, data.Timeouts.Read)
	resp.Diagnostics.Append(timeoutDiags...)
	if resp.Diagnostics.HasError() {
		return
	}
	readCtx, cancel := context.WithTimeout(ctx, readTimeout)
	defer cancel()

	var (
		got *proclassic.MobileDeviceInvitation
		err error
	)
	switch {
	case !data.ID.IsNull() && data.ID.ValueString() != "":
		got, err = d.client.GetMobileDeviceInvitationByID(readCtx, data.ID.ValueString())
	case !data.Invitation.IsNull() && data.Invitation.ValueString() != "":
		got, err = d.client.GetMobileDeviceInvitationByInvitation(readCtx, data.Invitation.ValueString())
	default:
		resp.Diagnostics.AddError("Missing mobile device invitation selector", "Exactly one of id or invitation must be supplied.")
		return
	}
	if err != nil {
		resp.Diagnostics.AddError("Unable to find Jamf Pro mobile device invitation", helpers.APIErrorDetail(err))
		return
	}
	assignMobileDeviceInvitationDataSourceModel(&data, got)

	tflog.Trace(ctx, "read Jamf Pro mobile device invitation data source", map[string]any{"id": data.ID.ValueString(), "invitation": data.Invitation.ValueString()})
	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}
