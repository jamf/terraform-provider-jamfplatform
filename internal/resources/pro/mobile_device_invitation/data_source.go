// MobileDeviceInvitationDataSource implements the Terraform data source for Jamf
// Pro mobile device invitations. Selection is by numeric `id` OR by the
// server-minted `invitation` code (the UI "Invitation ID") — exactly one of the
// two. There is no name lookup because invitations carry no name on the wire.
type MobileDeviceInvitationDataSource struct {
	client *proclassic.Client
}

var (
	_ datasource.DataSource                     = &MobileDeviceInvitationDataSource{}
	_ datasource.DataSourceWithConfigure        = &MobileDeviceInvitationDataSource{}
	_ datasource.DataSourceWithConfigValidators = &MobileDeviceInvitationDataSource{}
)

// NewMobileDeviceInvitationDataSource returns a new instance of
// MobileDeviceInvitationDataSource.
func NewMobileDeviceInvitationDataSource() datasource.DataSource {
	return &MobileDeviceInvitationDataSource{}
}

// Metadata sets the data source type name for the Terraform provider.
func (d *MobileDeviceInvitationDataSource) Metadata(ctx context.Context, req datasource.MetadataRequest, resp *datasource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_pro_mobile_device_invitation"
}

