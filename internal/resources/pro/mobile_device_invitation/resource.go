// minJamfProVersion is the minimum Jamf Pro tenant version required by this
// resource. Empty: the classic /mobiledeviceinvitations endpoint predates the
// provider's overall floor. The provider-level advisory still fires through
// providerdata.ConfigureProClassic when the tenant is below
// ProviderMinJamfProVersion.
const minJamfProVersion = ""

// MobileDeviceInvitationResource implements the Terraform resource for Jamf Pro
// mobile device enrollment invitations.
type MobileDeviceInvitationResource struct {
	client *proclassic.Client
}

var (
	_ resource.Resource                = &MobileDeviceInvitationResource{}
	_ resource.ResourceWithImportState = &MobileDeviceInvitationResource{}
	_ resource.ResourceWithIdentity    = &MobileDeviceInvitationResource{}
)

const (
	defaultCreateTimeout = 60 * time.Second
	defaultReadTimeout   = 60 * time.Second
	defaultUpdateTimeout = 60 * time.Second
	defaultDeleteTimeout = 60 * time.Second
)

// NewMobileDeviceInvitationResource returns a new instance of
// MobileDeviceInvitationResource.
func NewMobileDeviceInvitationResource() resource.Resource {
	return &MobileDeviceInvitationResource{}
}

// Metadata sets the resource type name for the Terraform provider.
func (r *MobileDeviceInvitationResource) Metadata(ctx context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_pro_mobile_device_invitation"
}

// IdentitySchema defines the identifier used for import and list results.
func (r *MobileDeviceInvitationResource) IdentitySchema(ctx context.Context, req resource.IdentitySchemaRequest, resp *resource.IdentitySchemaResponse) {
	resp.IdentitySchema = identityschema.Schema{
		Attributes: map[string]identityschema.Attribute{
			"id": identityschema.StringAttribute{
				Description:       "Jamf Pro mobile device invitation numeric ID used to uniquely reference the invitation.",
				RequiredForImport: true,
			},
		},
	}
}

